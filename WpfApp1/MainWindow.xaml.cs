Инструкция по использованию:

1. Запуск программы
   • Обязательно запускайте от имени администратора
     (правой кнопкой мыши на .exe → «Запуск от имени администратора»)
   • Без прав администратора часть данных может не отображаться или показывать 0%

2. Основные функции
   • Кнопка «Обновить» — мгновенное обновление всех данных
   • Галочка «Автообновление каждые 5 сек» — автоматическое обновление

3. Вкладки программы
   • Процессор: модель, количество ядер/потоков, базовая частота, текущая загрузка (%)
   • Память: общий объём ОЗУ, свободно/использовано, % загрузки, список модулей
   • Диски: список логических дисков, их объём и свободное место
   • Графический процессор: название видеокарты, объём видеопамяти, разрешение экрана, загрузка GPU (%)
   • Сеть: список сетевых адаптеров, MAC-адреса, статус подключения, скорость
   • Система: название и версия ОС, архитектура, имя компьютера, текущий пользователь

4. Экспорт отчёта
   • TXT — обычный текстовый файл
   • CSV — открывается в Excel
   • JSON — для программной обработки

5. Что делать, если данные не отображаются или показывают 0% / «—»:
   • Запустите программу от имени администратора
   • Создайте нагрузку на процессор (запуск нескольких программ / тест CPU)
   • Создайте нагрузку на видеокарту (игра, видео в 4K, тест FurMark, Unigine Heaven и т.д.)
   • Подождите 5–10 секунд или нажмите «Обновить» несколько раз
   • Если загрузка GPU всё равно 0% — проверьте в Диспетчере задач → вкладка «Производительность» → GPU

6. Возможные ограничения
   • В виртуальных машинах (VMware, VirtualBox, Hyper-V) и при удалённом доступе (RDP, Parsec) данные о GPU и памяти могут быть некорректными
   • Некоторые счётчики производительности требуют установленных драйверов NVIDIA/AMD
   • Объём видеопамяти иногда отображается не полностью — это особенность WMI

