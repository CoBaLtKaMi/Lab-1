Инструкция по использованию:

1. Запуск программы
   • Обязательно запускайте от имени администратора (правой кнопкой на .exe → «Запуск от имени администратора»)
   • Без прав администратора часть данных может не отображаться или показывать 0%

2. Основные функции
   • Кнопка «Обновить» — мгновенное обновление всех данных
   • Галочка «Автообновление каждые 5 сек» — автоматическое обновление

3. Вкладки программы
   • Процессор: модель, количество ядер/потоков, базовая частота, текущая загрузка (%)
